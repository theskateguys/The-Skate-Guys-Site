// Local generation and assertions only. No Google services, network or email delivery.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const logo = await fs.readFile(path.join(root, 'assets/theskateguys-1.png'));
const logoCode = `// Generated by automation/preview-booking-email.mjs from assets/theskateguys-1.png. Do not edit.\n// Original company PNG bytes, embedded as a CID attachment; no runtime image fetch or HTML data URI.\nfunction getTSGEmailLogo_() {\n  return Utilities.newBlob(Utilities.base64Decode('${logo.toString('base64')}'), 'image/png', 'tsg-logo.png');\n}\n`;
await fs.writeFile(path.join(root, 'automation/google-apps-script/EmailLogo.gs'), logoCode);
const sent = [];
const context = vm.createContext({
  Utilities: {base64Decode: value => Buffer.from(value, 'base64'), newBlob: (bytes, type, name) => ({bytes, type, name})},
  MailApp: {sendEmail: message => sent.push(message)}
});
vm.runInContext(await fs.readFile(path.join(root, 'automation/google-apps-script/Code.gs'), 'utf8'), context);
vm.runInContext(logoCode, context);
assert.deepEqual(context.getTSGEmailLogo_().bytes, logo, 'CID logo must preserve original bytes');
assert.equal(context.bookingEmailDate_('2027-01-05'), '5 January 2027');
assert.equal(context.bookingEmailDate_('2027-02-30'), '2027-02-30', 'Invalid dates are not silently changed');

const sample = {
  name: 'SAMPLE ONLY - Jordan Baptiste', leadId: 'TSG-PREVIEW-NOT-A-REAL-BOOKING', leadType: 'booking',
  whatsapp: '+18685550100', email: 'sample@example.test', location: 'Tobago', preferredArea: 'Black Rock (requested)',
  preferredDate: '2027-01-05', preferredTime: '10:30', participantCount: 2,
  participants: [
    {age: 30, experience: 'Beginner', rentals: 'No'},
    {age: 12, experience: 'First time', rentals: 'Yes', skateSize: '5', sizeSystem: 'UK child', guardianName: 'SAMPLE ONLY - Alex Baptiste', guardianPhone: '+18685550100'}
  ]
};
const stress = {...sample,
  name: 'SAMPLE ONLY - Alexandria-Christina Jean-Baptiste Montgomery-Williams and family',
  leadId: 'TSG-PREVIEW-' + 'LONGREFERENCE'.repeat(10),
  preferredArea: 'SAMPLE ONLY - A long requested area description for coordination, subject to TSG checking a suitable venue',
  participantCount: 3,
  participants: [...sample.participants, {age: 18, experience: 'Intermediate', rentals: 'Yes', skateSize: '10', sizeSystem: 'US men'}]
};
const previewDir = path.join(root, 'automation/email-previews');
await fs.mkdir(previewDir, {recursive: true});
for (const [name, lead, blocked] of [['booking-request', sample, false], ['stress-test', stress, false], ['blocked-images', sample, true]]) {
  const email = context.buildBookingAcknowledgement_(lead);
  assert.match(email.htmlBody, /Booking Request Received/);
  assert.match(email.htmlBody, /This is not a confirmed class/);
  assert.match(email.htmlBody, /No payment has been taken/);
  assert.match(email.body, /Awaiting availability confirmation/);
  assert.ok(email.body.includes('5 January 2027') && email.body.includes('Requested time (T&T local time)'));
  assert.ok(!email.body.includes('Record the agreed new expiry.'));
  assert.ok(email.body.includes("We'll confirm your revised credit expiry with you."));
  assert.ok(email.htmlBody.indexOf('Continue on WhatsApp') < email.htmlBody.indexOf('>Customer reference<'), 'Primary button precedes customer fields');
  assert.ok(email.body.indexOf('Continue on WhatsApp:') < email.body.indexOf('Customer reference:'), 'Plain text uses the same order');
  assert.ok(!/LOCAL EMAIL PREVIEW|NO EMAIL SENT|Browser preview, not/.test(email.htmlBody), 'Preview warnings never enter the delivery template');
  const rules = vm.runInContext('TSG_CREDIT_POLICY', context).split('\n');
  for (const rule of rules) {
    assert.ok(email.body.includes(rule), 'Plain text retains approved rule');
    assert.ok(email.htmlBody.includes(context.escapeHtml_(rule)), 'Selectable HTML retains approved rule');
  }
  const url = new URL(context.bookingEmailWhatsAppUrl_(lead));
  assert.equal(url.pathname, '/18682766878');
  assert.ok(url.searchParams.get('text').includes(lead.leadId));
  assert.ok(url.searchParams.get('text').includes('Participant 2 guardian'));
  const banner = `<p style="margin:0;padding:12px 16px;text-align:center;font:13px/1.6 Arial,sans-serif;color:#1d3035;background:#e8f8f7;"><strong>LOCAL EMAIL PREVIEW - SAMPLE DATA - NO EMAIL SENT</strong><br>${blocked ? 'Images intentionally unavailable. ' : ''}Browser preview, not an actual email-client test.</p>`;
  const html = email.htmlBody.replace('src="cid:tsgLogo"', `src="${blocked ? 'images-intentionally-blocked.png' : '../../assets/theskateguys-1.png'}"`)
    .replace(/(<body[^>]*>)/, `$1${banner}`);
  await fs.writeFile(path.join(previewDir, `${name}.html`), html);
  await fs.writeFile(path.join(previewDir, `${name}.txt`), 'LOCAL EMAIL PREVIEW - SAMPLE DATA - NO EMAIL SENT\n\n' + email.body + '\n');
}

const injection = '<img src=x onerror="alert(1)">&\'"';
const hostile = {...sample, name: injection, leadId: injection, preferredArea: injection,
  participants: [{...sample.participants[1], guardianName: injection, guardianPhone: injection, experience: injection, skateSize: injection, sizeSystem: injection}]};
const escaped = context.buildBookingAcknowledgement_(hostile);
assert.ok(!escaped.htmlBody.includes(injection));
assert.ok(escaped.htmlBody.includes('&lt;img src=x onerror=&quot;alert(1)&quot;&gt;&amp;&#39;&quot;'));
assert.ok(!/<script|onerror="alert/.test(escaped.htmlBody));
context.sendLeadConfirmation_(sample);
assert.equal(sent.length, 1, 'One mocked acknowledgement');
assert.deepEqual(sent[0].inlineImages.tsgLogo.bytes, logo);
assert.ok(sent[0].htmlBody.includes('cid:tsgLogo'));
assert.ok(sent[0].body.includes(sample.leadId));
assert.ok(!/data:image|background-image|<script|<link/.test(sent[0].htmlBody));
assert.ok(Buffer.byteLength(sent[0].htmlBody) < 80000, 'Keep HTML below common clipping thresholds');
context.sendLeadConfirmation_({...sample, email: ''});
assert.equal(sent.length, 1, 'No email address still means no acknowledgement');
context.sendLeadConfirmation_({...sample, leadType: 'email'});
assert.equal(sent.length, 2);
assert.equal(sent[1].htmlBody, undefined, 'Other existing email flow unchanged');
console.log('PASS: local HTML/plain-text previews, original CID PNG bytes, escaping, policy, participants, request reference, WhatsApp and mocked mail assembly. No real emails sent.');
